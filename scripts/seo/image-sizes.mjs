/**
 * Writes src/content/blogImageSizes.ts: natural width and height of every image used in blog markdown, so articles
 * render <img width height> and never shift the layout while images load.
 * Run: npm run seo:images (a test fails when the file is stale or an image has no entry).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const blogsDir = path.join(root, 'public/content/blogs');

/** PNG, JPEG or WebP dimensions from the file header; null for anything else (SVG scales, so it needs none) */
export function imageSize(file) {
  const b = fs.readFileSync(file);
  if (b.length > 24 && b.toString('latin1', 1, 4) === 'PNG') return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
  if (b[0] === 0xff && b[1] === 0xd8) {
    let i = 2;
    while (i < b.length) {
      if (b[i] !== 0xff) return null;
      const marker = b[i + 1];
      if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) return { height: b.readUInt16BE(i + 5), width: b.readUInt16BE(i + 7) };
      i += 2 + b.readUInt16BE(i + 2);
    }
  }
  if (b.toString('latin1', 0, 4) === 'RIFF' && b.toString('latin1', 8, 12) === 'WEBP' && b.toString('latin1', 12, 16) === 'VP8X') {
    return { width: 1 + b.readUIntLE(24, 3), height: 1 + b.readUIntLE(27, 3) };
  }
  return null;
}

export function collectSizes() {
  const sizes = {};
  for (const name of fs.readdirSync(blogsDir).filter((n) => n.endsWith('.md')).sort()) {
    const md = fs.readFileSync(path.join(blogsDir, name), 'utf8').replace(/```[\s\S]*?```/g, '');
    for (const m of md.matchAll(/!\[[^\]]*\]\((\/[^)\s]+)/g)) {
      const src = m[1];
      const file = path.join(root, 'public', src);
      if (sizes[src] || !fs.existsSync(file)) continue;
      const size = imageSize(file);
      if (size) sizes[src] = size;
    }
  }
  return Object.fromEntries(Object.entries(sizes).sort(([a], [b]) => a.localeCompare(b)));
}

export function renderModule(sizes) {
  const rows = Object.entries(sizes).map(([src, s]) => `  '${src}': { width: ${s.width}, height: ${s.height} },`).join('\n');
  return `/**
 * Natural size of every image used in blog markdown (width and height attributes stop layout shift).
 * GENERATED by scripts/seo/image-sizes.mjs: run "npm run seo:images" after adding blog images.
 */
export const BLOG_IMAGE_SIZES: Record<string, { width: number; height: number }> = {
${rows}
};

export const blogImageSize = (src: string | undefined): { width: number; height: number } | undefined => (src ? BLOG_IMAGE_SIZES[src] : undefined);
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = path.join(root, 'src/content/blogImageSizes.ts');
  fs.writeFileSync(out, renderModule(collectSizes()));
  console.log(`wrote ${path.relative(root, out)}`);
}
