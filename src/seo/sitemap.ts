/**
 * Builders for sitemap.xml, robots.txt and llms.txt, generated from the page list in ./pages.ts.
 * Run `npm run seo:files` to write them to /public (the build does this automatically). Pure string functions.
 */

import { SEO_CONFIG } from './config';
import { absoluteUrl, canonicalFor } from './meta';
import { getSeoPages, type SeoPage } from './pages';
import { BLOG_POSTS } from '@/constants/blogs';

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function buildSitemapXml(pages: SeoPage[] = getSeoPages()): string {
  const rows = pages
    .filter((p) => !p.noindex)
    .map((p) => {
      const images = (p.images ?? [])
        .map((i) => `    <image:image>\n      <image:loc>${esc(absoluteUrl(i.path))}</image:loc>\n      <image:title>${esc(i.title)}</image:title>\n    </image:image>`)
        .join('\n');
      return [
        '  <url>',
        `    <loc>${esc(canonicalFor(p.path))}</loc>`,
        `    <lastmod>${p.lastmod}</lastmod>`,
        `    <changefreq>${p.changefreq}</changefreq>`,
        `    <priority>${p.priority.toFixed(1)}</priority>`,
        ...(images ? [images] : []),
        '  </url>',
      ].join('\n');
    });
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/seo/build-files.mjs from src/seo/pages.ts. Do not edit by hand: run "npm run seo:files". -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${rows.join('\n')}
</urlset>
`;
}

/** Paths that must never be crawled or indexed */
export const ROBOTS_DISALLOW = ['/admin', '/embed/', '/api/'] as const;

/** AI search and answer crawlers that are explicitly welcome (blog guides and tools are meant to be cited) */
export const AI_CRAWLERS = ['GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-SearchBot', 'PerplexityBot', 'Google-Extended', 'Applebot-Extended'] as const;

export function buildRobotsTxt(): string {
  const disallow = ROBOTS_DISALLOW.map((p) => `Disallow: ${p}`).join('\n');
  const ai = AI_CRAWLERS.map((bot) => `User-agent: ${bot}\nAllow: /\n${disallow}\n`).join('\n');
  return `# robots.txt for ${SEO_CONFIG.siteName}
# Generated by scripts/seo/build-files.mjs from src/seo/sitemap.ts. Do not edit by hand: run "npm run seo:files".

User-agent: *
Allow: /
${disallow}

# AI search and answer engines: allowed, so guides and tools can be read and cited
${ai}
Sitemap: ${SEO_CONFIG.siteUrl}/sitemap.xml
`;
}

/** llms.txt: a short, plain index of the best pages for AI assistants (https://llmstxt.org) */
export function buildLlmsTxt(pages: SeoPage[] = getSeoPages()): string {
  const line = (p: SeoPage, label?: string) => `- [${label ?? p.title.replace(/\s*\|\s*Vayu Packaging Solutions$/, '')}](${canonicalFor(p.path)}): ${p.description}`;
  const byKind = (kind: SeoPage['kind']) => pages.filter((p) => p.kind === kind);
  const key = pages.filter((p) => ['home', 'about', 'products', 'services', 'contact', 'quote', 'locations'].includes(p.kind));
  const blog = BLOG_POSTS.map((post) => pages.find((p) => p.kind === 'blog' && p.slug === post.slug)).filter((p): p is SeoPage => !!p);
  return `# ${SEO_CONFIG.siteName}

> Corrugated box and packaging materials supplier in Ahmedabad, Gujarat, India. Custom sizes, 3, 5 and 7-ply boxes, printed and die-cut boxes, tapes, stretch film, bubble wrap and strapping. Also a free 3D box designer that folds a box on screen and exports a dieline and spec sheet.

## Key pages
${key.map((p) => line(p)).join('\n')}

## Free tools
${[...byKind('designer'), ...byKind('finder'), ...byKind('tools'), ...byKind('tool')].map((p) => line(p)).join('\n')}

## Box styles (3D designer landing pages)
${byKind('landing').map((p) => line(p)).join('\n')}

## Guides
${blog.map((p) => line(p)).join('\n')}
`;
}
